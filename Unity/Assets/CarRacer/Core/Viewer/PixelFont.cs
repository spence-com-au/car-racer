        /// <summary>How many glyphs the font has (printable ASCII).</summary>
        public static int GlyphCount => Glyphs.Length / GlyphWidth;

        /// <summary>Whether the pixel at (<paramref name="column"/>, <paramref name="row"/>) of <paramref name="c"/>'s glyph is set.</summary>
        public static bool IsSet(char c, int column, int row)
        {
            if (column < 0 || column >= GlyphWidth || row < 0 || row >= GlyphHeight + DescenderRows)
            {
                return false;
            }

            return (Glyphs[GlyphIndex(c) * GlyphWidth + column] & (1 << row)) != 0;
        }

        /// <summary>The width of <paramref name="text"/> in pixels at <paramref name="scale"/>, without trailing space.</summary>
        public static int Measure(string text, int scale)
        {
            if (string.IsNullOrEmpty(text))
            {
                return 0;
            }

            return (text.Length * (GlyphWidth + Spacing) - Spacing) * scale;
        }

        /// <summary>Draws <paramref name="text"/> with its top-left corner at (<paramref name="x"/>, <paramref name="y"/>); returns the x just past it.</summary>
        public static int Draw(RgbImage image, int x, int y, string text, int scale, Rgb colour)
        {
            if (string.IsNullOrEmpty(text))
            {
                return x;
            }

            foreach (char c in text)
            {
                int glyph = GlyphIndex(c) * GlyphWidth;
                for (int column = 0; column < GlyphWidth; column++)
                {
                    int bits = Glyphs[glyph + column];
                    for (int row = 0; row < GlyphHeight + DescenderRows; row++)
                    {
                        if ((bits & (1 << row)) != 0)
                        {
                            image.FillRect(x + column * scale, y + row * scale, scale, scale, colour);
                        }
                    }
                }

                x += (GlyphWidth + Spacing) * scale;
            }

            return x - Spacing * scale;
        }

        /// <summary>
        /// Shortens <paramref name="text"/> with a trailing "." so it fits <paramref name="maxWidth"/>
        /// pixels at <paramref name="scale"/>.
        /// </summary>
        public static string Fit(string text, int scale, int maxWidth)
        {
            if (string.IsNullOrEmpty(text) || Measure(text, scale) <= maxWidth)
            {
                return text ?? string.Empty;
            }

            int fits = Math.Max(0, (maxWidth / scale + Spacing) / (GlyphWidth + Spacing));
            return fits <= 1 ? text.Substring(0, Math.Min(fits, text.Length)) : text.Substring(0, fits - 1) + ".";
        }

        private static int GlyphIndex(char c) => c >= First && c - First < GlyphCount ? c - First : '?' - First;
    }
